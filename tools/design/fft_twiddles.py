"""Writes dsp/src/dsp_fft_tables.c: cos and sin of 2 pi k / 2048 for k in [0, 1024), as float32.

One table serves every real FFT size from 16 to 2048 points (a size-n transform reads it with a
stride of 2048 / n). The values come from here, not from the C library at start-up, so the PC,
the M7 and the M4 use bit-identical twiddles whatever their libm does.

  python tools/design/fft_twiddles.py
"""
import pathlib

import numpy as np

MAX_N = 2048
ROOT = pathlib.Path(__file__).resolve().parents[2]


def table():
    k = np.arange(MAX_N // 2, dtype=np.float64)
    angle = 2.0 * np.pi * k / MAX_N
    return np.cos(angle).astype(np.float32), np.sin(angle).astype(np.float32)


def c_array(name, values):
    lines = [f"const float {name}[kDspFftTableLen] = {{"]
    for i in range(0, len(values), 6):
        chunk = ", ".join(f"{float(v):.9e}f" for v in values[i:i + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    cos, sin = table()
    text = "\n".join([
        "/* Generated by tools/design/fft_twiddles.py; do not edit. cos and sin of 2 pi k / 2048,",
        " * k in [0, 1024), rounded to float32 from double precision. */",
        '#include "dsp/dsp_fft.h"',
        "",
        c_array("kDspFftCos", cos),
        "",
        c_array("kDspFftSin", sin),
        "",
    ])
    out = ROOT / "dsp/src/dsp_fft_tables.c"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
