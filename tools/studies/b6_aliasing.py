"""Batch 6 study: aliasing of the saturator in each mode.

    python tools/studies/b6_aliasing.py [--out docs/results/b6_aliasing.md]

A coherent sine at -0.9 dBFS through tanh with 12 dB of drive, at 48 kHz. Reported: the
strongest component below 20 kHz that is not a harmonic of the input, relative to the
fundamental (dB; lower is better). Above 20 kHz is ignored: the half-band filters let 24 to 28
kHz fold into 20 to 24 kHz by design.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT / "tests" / "unit"))

import dsplib  # noqa: E402
import dsplib_b6 as b6  # noqa: E402
from test_oversample_saturate import alias_db  # noqa: E402

MODES = [("Plain (1x)", 0), ("ADAA (1x)", 3), ("2x", 1), ("4x", 2)]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "docs/results/b6_aliasing.md"))
    args = parser.parse_args()
    lib = b6.bind(dsplib.load())
    lines = ["# Batch 6: aliasing of the saturator", "",
             "Strongest inharmonic component below 20 kHz, dB relative to the fundamental, for a",
             "-0.9 dBFS sine through tanh with 12 dB of drive at 48 kHz (lower is better).",
             "Generated by `python tools/studies/b6_aliasing.py`.", "",
             "| Input | " + " | ".join(name for name, _ in MODES) + " |",
             "|---|" + "---|" * len(MODES)]
    for f0 in (1000.0, 2000.0, 5000.0, 10000.0, 15000.0):
        cells = [f"{alias_db(lib, mode, f0):.1f}" for _, mode in MODES]
        lines.append(f"| {f0 / 1000:g} kHz | " + " | ".join(cells) + " |")
        print(lines[-1])
    pathlib.Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written to {args.out}")


if __name__ == "__main__":
    main()
