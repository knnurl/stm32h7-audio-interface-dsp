"""Batch 3 study: how far bilinear (RBJ) peaks depart from their analogue prototype near Nyquist.

    python tools/studies/b3_cramping.py [--out docs/results/b3_cramping.md]

Analogue prototype of the peak: H(s) = (s^2 + s (A/Q) w0 + w0^2) / (s^2 + s w0 / (A Q) + w0^2),
A = 10^(gain/40). The digital design is the C library's dsp_coef_peak. Errors in dB, digital
minus analogue, at f0 and at frequencies around it.
"""
import argparse
import math
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests"))

import dsplib  # noqa: E402
from ref import coef  # noqa: E402


def analogue_db(f, f0, q, gain_db):
    a = 10 ** (gain_db / 40)
    s = 1j * 2 * math.pi * f
    w0 = 2 * math.pi * f0
    h = (s * s + s * (a / q) * w0 + w0 * w0) / (s * s + s * w0 / (a * q) + w0 * w0)
    return 20 * np.log10(abs(h))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "docs/results/b3_cramping.md"))
    args = parser.parse_args()
    lib = dsplib.load()
    lines = [
        "# Batch 3: cramping of bilinear peaks near Nyquist",
        "",
        "Digital (RBJ cookbook, `dsp_coef_peak`) minus analogue prototype, in dB, for a +12 dB",
        "peak with Q 1. Generated by `python tools/studies/b3_cramping.py`.",
        "",
        "| fs | f0 | at f0 / 2 | at f0 | at 1.2 f0 | at 20 kHz |",
        "|---|---|---|---|---|---|",
    ]
    for fs in (48000.0, 96000.0):
        for f0 in (1000.0, 5000.0, 10000.0, 15000.0, 18000.0):
            sec = dsplib.design(lib, "peak", fs, f0, 1.0, 12.0)
            cells = []
            for f in (f0 / 2, f0, 1.2 * f0, 20000.0):
                if f >= fs / 2:
                    cells.append("n/a")
                    continue
                d = coef.magnitude_db([sec], fs, f) - analogue_db(f, f0, 1.0, 12.0)
                cells.append(f"{d:+.2f}")
            lines.append(f"| {fs / 1000:g} kHz | {f0 / 1000:g} kHz | " + " | ".join(cells) + " |")
            print(lines[-1])
    out = pathlib.Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
