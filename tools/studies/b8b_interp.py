"""Batch 8b study: fractional delay reads, error at a fixed delay and noise on a swept delay.

    python tools/studies/b8b_interp.py [--out docs/results/b8b_interp.md]

Everything runs through the C library (dsp_delayline_f32_process) at 48 kHz.
1. Fixed delay: a sine read at a fixed fractional delay; the error is |H - e^(-j w d)|, the
   distance of the measured complex response from an ideal delay, in dB (magnitude and phase
   errors together).
2. Swept delay: a sine read at d(n) = 960 + 240 sin(2 pi 2 n / fs) samples (20 ms +/- 5 ms at
   2 Hz, a deep chorus). The ideal output is the sine at time n - d(n), computed exactly; the
   error power is reported relative to the signal (dB; lower is better).
"""
import argparse
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests"))

import dsplib  # noqa: E402
import dsplib_b8b as b8  # noqa: E402

FS = 48000.0
METHODS = [("Linear", b8.INTERP_LINEAR), ("Lagrange 3", b8.INTERP_LAGRANGE),
           ("All-pass 1", b8.INTERP_ALLPASS)]


def fixed_error_db(lib, interp, f, d):
    n = 16384
    t = np.arange(n)
    x = (0.5 * np.sin(2 * np.pi * f * t / FS)).astype(np.float32)
    y = b8.Delayline(lib, 2048).process(interp, x, np.full(n, d))[2000:].astype(np.float64)
    tt = t[2000:] / FS
    basis = np.stack([np.sin(2 * np.pi * f * tt), np.cos(2 * np.pi * f * tt)], axis=1)
    (a, b), *_ = np.linalg.lstsq(basis, y, rcond=None)
    h = complex(a, b) / 0.5  # a sin + b cos = Im(h e^{jwt}) with h = a + j b
    ideal = np.exp(-1j * 2 * np.pi * f * d / FS)
    return 20 * np.log10(abs(h - ideal))


def swept_error_db(lib, interp, f):
    n = 96000
    t = np.arange(n, dtype=np.float64)
    d = 960 + 240 * np.sin(2 * np.pi * 2 * t / FS)
    x = (0.5 * np.sin(2 * np.pi * f * t / FS)).astype(np.float32)
    y = b8.Delayline(lib, 2048).process(interp, x, d.astype(np.float32)).astype(np.float64)
    ideal = 0.5 * np.sin(2 * np.pi * f * (t - d.astype(np.float32).astype(np.float64)) / FS)
    s = slice(4800, n)
    err = y[s] - ideal[s]
    return 10 * np.log10(np.mean(err ** 2) / np.mean(ideal[s] ** 2))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "docs/results/b8b_interp.md"))
    args = parser.parse_args()
    lib = b8.bind(dsplib.load())
    names = [name for name, _ in METHODS]
    lines = ["# Batch 8b: fractional delay reads", "",
             "Generated by `python tools/studies/b8b_interp.py`, through the C library at 48 kHz.",
             "", "## 1. Error against an ideal delay, fixed fraction", "",
             "|H - e^(-j w d)| in dB (lower is better).", "",
             "| Fraction | Frequency | " + " | ".join(names) + " |",
             "|---|---|" + "---|" * len(METHODS)]
    for frac in (0.25, 0.5):
        for f in (1000.0, 5000.0, 10000.0, 15000.0, 20000.0):
            cells = [f"{fixed_error_db(lib, m, f, 100 + frac):.1f}" for _, m in METHODS]
            lines.append(f"| {frac} | {f / 1000:g} kHz | " + " | ".join(cells) + " |")
            print(lines[-1])
    lines += ["", "## 2. Error on a swept delay (20 ms +/- 5 ms at 2 Hz)", "",
              "Error power relative to the signal, dB (lower is better).", "",
              "| Frequency | " + " | ".join(names) + " |", "|---|" + "---|" * len(METHODS)]
    for f in (100.0, 1000.0, 5000.0, 10000.0):
        cells = [f"{swept_error_db(lib, m, f):.1f}" for _, m in METHODS]
        lines.append(f"| {f / 1000:g} kHz | " + " | ".join(cells) + " |")
        print(lines[-1])
    lines += ["", "Cost per read: linear 2 taps and 1 multiply-add; Lagrange 4 taps and about 10",
              "multiplies; all-pass 2 taps, 2 multiplies, a divide (eta) and one state word."]
    pathlib.Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written to {args.out}")


if __name__ == "__main__":
    main()
